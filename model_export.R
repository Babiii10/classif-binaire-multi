################################################################################
# Description: Export trained models to standardized formats for deployment
# Formats supported:
#   - PMML (Predictive Model Markup Language) - industry standard
#   - RDS (R native format) - with metadata
#   - JSON (model parameters and structure)
#   - ONNX (Open Neural Network Exchange) - for deep learning models
#
# Dependencies (optional):
#   - r2pmml: PMML export for various models
#   - pmml: Alternative PMML export
#   - jsonlite: JSON export
################################################################################

# Check optional packages
EXPORT_AVAILABLE <- list(
  r2pmml = requireNamespace("r2pmml", quietly = TRUE),
  pmml = requireNamespace("pmml", quietly = TRUE),
  jsonlite = requireNamespace("jsonlite", quietly = TRUE)
)

if (!any(unlist(EXPORT_AVAILABLE[c("r2pmml", "pmml")]))) {
  message("NOTE: PMML export requires 'r2pmml' or 'pmml' package")
  message("  install.packages(c('r2pmml', 'pmml'))")
}

