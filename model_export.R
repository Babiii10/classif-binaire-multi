#' Export model to PMML format
#'
#' @param model Trained model object
#' @param model_type Type of model ("randomforest", "xgboost", "svm", etc.)
#' @param data Training data (for schema information)
#' @param target_variable Name of target variable (default: "group")
#' @param output_file Path to save PMML file
#' @param model_name Optional model name for metadata
#' @return TRUE if successful, FALSE otherwise
export_to_pmml <- function(model, model_type, data, target_variable = "group",
                          output_file = "model.pmml", model_name = NULL) {

  if (!EXPORT_AVAILABLE$pmml && !EXPORT_AVAILABLE$r2pmml) {
    warning("PMML export requires 'pmml' or 'r2pmml' package")
    return(FALSE)
  }

  tryCatch({

    message("Exporting model to PMML format...")

    # Prepare data schema
    feature_names <- setdiff(names(data), c(target_variable, "group", "Group", "class", "Class"))
    X <- data[, feature_names, drop = FALSE]
    y <- data[[target_variable]]

    # Select appropriate PMML export method
    if (model_type == "randomforest" && EXPORT_AVAILABLE$pmml) {
      # Use pmml package for random forest

      pmml_obj <- pmml::pmml(
        model,
        model.name = if(is.null(model_name)) paste0("RandomForest_", Sys.Date()) else model_name,
        app.name = "Shiny Classification App",
        description = paste("Random Forest classification model -", Sys.Date()),
        copyright = paste("Generated on", Sys.time())
      )

      pmml::saveXML(pmml_obj, file = output_file)

    } else if (model_type %in% c("elasticnet", "lasso", "ridge") && EXPORT_AVAILABLE$pmml) {
      # GLM models

      pmml_obj <- pmml::pmml(
        model,
        model.name = if(is.null(model_name)) paste0("GLM_", Sys.Date()) else model_name,
        app.name = "Shiny Classification App",
        description = paste("Elastic Net classification model -", Sys.Date())
      )

      pmml::saveXML(pmml_obj, file = output_file)

    } else if (model_type %in% c("svm", "svmlinear", "svmradial") && EXPORT_AVAILABLE$pmml) {
      # SVM models

      pmml_obj <- pmml::pmml(
        model,
        model.name = if(is.null(model_name)) paste0("SVM_", Sys.Date()) else model_name,
        app.name = "Shiny Classification App",
        description = paste("SVM classification model -", Sys.Date())
      )

      pmml::saveXML(pmml_obj, file = output_file)

    } else {
      # Fallback: create custom PMML structure
      message("Model type not directly supported for PMML - creating custom structure")
      create_custom_pmml(model, model_type, X, y, output_file, model_name)
    }

    message(paste("✓ Model exported to PMML:", output_file))
    return(TRUE)

  }, error = function(e) {
    warning(paste("PMML export failed:", e$message))
    message("  Attempting alternative export method...")

    # Try alternative export
    return(export_to_rds_with_metadata(model, model_type, data, gsub("\\.pmml$", ".rds", output_file)))
  })
}

#' Create custom PMML structure for unsupported models
create_custom_pmml <- function(model, model_type, X, y, output_file, model_name) {

  # Basic PMML template
  pmml_content <- paste0('<?xml version="1.0" encoding="UTF-8"?>
<PMML version="4.4" xmlns="http://www.dmg.org/PMML-4_4">
  <Header copyright="Generated by Shiny Classification App" description="', model_type, ' classification model">
    <Application name="Shiny Classification App" version="2.0"/>
    <Timestamp>', Sys.time(), '</Timestamp>
  </Header>
  <DataDictionary numberOfFields="', ncol(X) + 1, '">
    <DataField name="', names(y)[1], '" optype="categorical" dataType="string">
')

  # Add target levels
  for (level in levels(y)) {
    pmml_content <- paste0(pmml_content, '      <Value value="', level, '"/>\n')
  }

  pmml_content <- paste0(pmml_content, '    </DataField>\n')

  # Add feature fields
  for (feat in names(X)) {
    feat_type <- class(X[[feat]])[1]
    pmml_type <- if (feat_type %in% c("numeric", "integer")) "double" else "string"
    pmml_optype <- if (feat_type %in% c("numeric", "integer")) "continuous" else "categorical"

    pmml_content <- paste0(pmml_content, '    <DataField name="', feat,
                          '" optype="', pmml_optype, '" dataType="', pmml_type, '"/>\n')
  }

  pmml_content <- paste0(pmml_content, '  </DataDictionary>
  <!-- Model Details: ', model_type, ' -->
  <!-- Note: Full model serialization requires model-specific PMML converter -->
  <!-- This file contains data schema only - use RDS export for complete model -->
</PMML>
')

  # Write to file
  writeLines(pmml_content, output_file)
  message("  Note: Custom PMML contains schema only - use RDS for complete model")
}

