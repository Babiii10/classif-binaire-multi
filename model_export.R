#' Export model to RDS with comprehensive metadata
#'
#' @param model Trained model object
#' @param model_type Model type
#' @param data Training data
#' @param output_file Output file path
#' @param include_data Whether to include training data (default: FALSE)
#' @return TRUE if successful
export_to_rds_with_metadata <- function(model, model_type, data, output_file = "model.rds",
                                        include_data = FALSE) {

  tryCatch({

    # Create metadata
    metadata <- list(
      model_type = model_type,
      created_date = Sys.time(),
      r_version = R.version.string,
      feature_names = setdiff(names(data), c("group", "Group", "class", "Class")),
      n_features = length(setdiff(names(data), c("group", "Group", "class", "Class"))),
      n_classes = length(levels(data$group)),
      class_levels = levels(data$group),
      training_samples = nrow(data),
      package_versions = list(
        randomForest = if(model_type == "randomforest") as.character(packageVersion("randomForest")) else NULL,
        xgboost = if(model_type == "xgboost") as.character(packageVersion("xgboost")) else NULL,
        e1071 = if(grepl("svm", model_type)) as.character(packageVersion("e1071")) else NULL,
        glmnet = if(model_type %in% c("elasticnet", "lasso", "ridge")) as.character(packageVersion("glmnet")) else NULL
      )
    )

    # Create model package
    model_package <- list(
      model = model,
      metadata = metadata,
      training_data = if(include_data) data else NULL
    )

    # Save to RDS
    saveRDS(model_package, file = output_file)

    message(paste("✓ Model exported to RDS:", output_file))
    message("  Metadata included: model type, features, class levels, package versions")

    return(TRUE)

  }, error = function(e) {
    warning(paste("RDS export failed:", e$message))
    return(FALSE)
  })
}

#' Load model from RDS with validation
load_model_from_rds <- function(input_file) {

  tryCatch({

    model_package <- readRDS(input_file)

    # Validate structure
    if (!is.list(model_package) || is.null(model_package$model)) {
      stop("Invalid model file structure")
    }

    # Print metadata
    if (!is.null(model_package$metadata)) {
      message("\n=== Model Metadata ===")
      message("Model Type: ", model_package$metadata$model_type)
      message("Created: ", model_package$metadata$created_date)
      message("Features: ", model_package$metadata$n_features)
      message("Classes: ", model_package$metadata$n_classes)
      message("Training Samples: ", model_package$metadata$training_samples)
      message("====================\n")
    }

    return(model_package)

  }, error = function(e) {
    stop(paste("Failed to load model:", e$message))
  })
}

