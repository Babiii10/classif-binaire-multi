#' Export model to multiple formats simultaneously
#'
#' @param model Trained model
#' @param model_type Model type
#' @param data Training data
#' @param output_dir Directory to save exports
#' @param formats Vector of formats: c("pmml", "rds", "json")
#' @param model_name Optional model name
#' @return List of export results
export_model <- function(model, model_type, data, output_dir = "exports",
                        formats = c("rds", "json"), model_name = NULL) {

  # Create output directory
  if (!dir.exists(output_dir)) {
    dir.create(output_dir, recursive = TRUE)
  }

  # Generate base filename
  if (is.null(model_name)) {
    model_name <- paste0(model_type, "_", format(Sys.Date(), "%Y%m%d"))
  }

  results <- list()

  message("\n=== Exporting Model ===")
  message("Model: ", model_name)
  message("Formats: ", paste(formats, collapse = ", "))
  message("Output directory: ", output_dir)
  message("")

  # PMML export
  if ("pmml" %in% formats) {
    pmml_file <- file.path(output_dir, paste0(model_name, ".pmml"))
    results$pmml <- export_to_pmml(model, model_type, data, output_file = pmml_file, model_name = model_name)
  }

  # RDS export
  if ("rds" %in% formats) {
    rds_file <- file.path(output_dir, paste0(model_name, ".rds"))
    results$rds <- export_to_rds_with_metadata(model, model_type, data, output_file = rds_file)
  }

  # JSON export
  if ("json" %in% formats) {
    json_file <- file.path(output_dir, paste0(model_name, ".json"))
    results$json <- export_to_json(model, model_type, data, output_file = json_file)
  }

  message("\n=== Export Summary ===")
  message("PMML: ", if(results$pmml %||% FALSE) "✓ Success" else "✗ Failed or not requested")
  message("RDS:  ", if(results$rds %||% FALSE) "✓ Success" else "✗ Failed or not requested")
  message("JSON: ", if(results$json %||% FALSE) "✓ Success" else "✗ Failed or not requested")
  message("===================\n")

  return(results)
}

