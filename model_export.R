#' Export model configuration and parameters to JSON
#'
#' @param model Trained model
#' @param model_type Model type
#' @param data Training data
#' @param output_file Output JSON file
#' @param include_predictions Whether to include predictions on training data
#' @return TRUE if successful
export_to_json <- function(model, model_type, data, output_file = "model.json",
                          include_predictions = FALSE) {

  if (!EXPORT_AVAILABLE$jsonlite) {
    warning("JSON export requires 'jsonlite' package")
    return(FALSE)
  }

  tryCatch({

    # Extract model parameters based on type
    params <- extract_model_parameters(model, model_type)

    # Create JSON structure
    json_data <- list(
      metadata = list(
        model_type = model_type,
        created_date = as.character(Sys.time()),
        r_version = R.version.string,
        n_features = length(setdiff(names(data), c("group", "Group", "class", "Class"))),
        n_classes = length(levels(data$group)),
        class_levels = levels(data$group)
      ),
      parameters = params,
      feature_names = setdiff(names(data), c("group", "Group", "class", "Class"))
    )

    # Add predictions if requested
    if (include_predictions) {
      preds <- predict(model, data, type = "prob")
      json_data$training_predictions <- head(preds, 100)  # Limit to first 100
    }

    # Write to JSON
    jsonlite::write_json(
      json_data,
      path = output_file,
      pretty = TRUE,
      auto_unbox = TRUE
    )

    message(paste("✓ Model configuration exported to JSON:", output_file))
    return(TRUE)

  }, error = function(e) {
    warning(paste("JSON export failed:", e$message))
    return(FALSE)
  })
}

#' Extract model parameters for JSON export
extract_model_parameters <- function(model, model_type) {

  params <- list()

  tryCatch({

    if (model_type == "randomforest") {
      params <- list(
        ntree = model$ntree,
        mtry = model$mtry,
        nodesize = model$nodesize,
        importance = if(!is.null(model$importance)) TRUE else FALSE
      )

    } else if (model_type == "xgboost") {
      params <- list(
        nrounds = model$niter,
        params = model$params
      )

    } else if (model_type %in% c("svm", "svmlinear", "svmradial")) {
      params <- list(
        kernel = model$kernel,
        cost = model$cost,
        gamma = if(!is.null(model$gamma)) model$gamma else NULL,
        nSV = model$nSV
      )

    } else if (model_type %in% c("elasticnet", "lasso", "ridge")) {
      params <- list(
        alpha = model$alpha,
        lambda_min = min(model$lambda),
        lambda_max = max(model$lambda),
        n_lambda = length(model$lambda)
      )
    }

  }, error = function(e) {
    warning(paste("Could not extract all parameters:", e$message))
  })

  return(params)
}

